    out = rewrite_paths("".join(parts))
    if article:
        out = re.sub(r'<article class="doc__card">.*?</article>', lambda m: article, out, count=1, flags=re.S)
        missing = []
    path = os.path.normpath(os.path.join(ROOT, "kz", out_name or name))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8").write(out)
    return list(dict.fromkeys(missing))


